export interface FieldError {
  path: string;
  reason: string;
}

/**
 * Standard RFC 9457 Problem Detail JSON structure
 * Returned by all API error conditions.
 */
export interface ProblemDetail {
  type: string;
  title: string;
  status: number;
  detail: string;
  instance: string;
  code: OrcaErrorCode | string;
  request_id: string;
  errors?: FieldError[];
  retryable: boolean;
}

